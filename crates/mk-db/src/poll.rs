//! Poll (`poll`) + poll votes (`poll_vote`): note.ts acceptance slice.
//!
//! Upstream: `NoteCreateService.insertNote` (transactional note+poll row),
//! `NoteEntityService.populatePoll` (choices with live votes + per-viewer
//! `isVoted`), `endpoints/notes/polls/vote.ts` (dedup + expiry validation,
//! `votes[$1] = votes[$1] + 1` count bump). Choices are stored in a
//! `varchar[]` column with the matching-length integer `votes` array
//! (1-based when addressed from SQL, 0-based from the Rust side).
//! `expiresAt` crosses this boundary as epoch milliseconds (the workspace
//! pins sqlx without the chrono/time decoders; ms_to_iso lives in mk-core).

use sqlx::PgPool;

/// One `poll` row. `votes[i]` counts votes for `choices[i]`; `expires_at_ms`
/// is the epoch-millisecond deadline (None → never expires).
#[derive(Debug, sqlx::FromRow)]
pub struct PollRow {
    // decodes from the `("noteId") AS "note_id"` alias below (NOTE_COLS
    // convention); a `#[sqlx(rename = "noteId")]` here made every
    // find_poll_by_note decode fail "no column found for name: noteId" —
    // the 500 on pack of any poll-attached note.
    pub note_id: String,
    #[sqlx(rename = "expires_at_ms")]
    pub expires_at_ms: Option<i64>,
    pub multiple: bool,
    pub choices: Vec<String>,
    pub votes: Vec<i32>,
}

const POLL_COLS: &str = r#"("noteId") AS "note_id",
    floor(extract(epoch from "expiresAt") * 1000)::bigint AS "expires_at_ms",
    "multiple", "choices", "votes""#;

pub async fn insert_poll(
    pool: &PgPool,
    note_id: &str,
    choices: &[String],
    multiple: bool,
    // Epoch-ms deadline; None → never expires.
    expires_at_ms: Option<i64>,
    note_visibility: &str,
    user_id: &str,
) -> Result<(), sqlx::Error> {
    let votes = vec![0i32; choices.len()];
    sqlx::query(
        r#"
        INSERT INTO "poll" ("noteId", "expiresAt", "multiple", "choices", "votes",
                            "noteVisibility", "userId", "userHost", "channelId")
        VALUES ($1, to_timestamp($2::double precision / 1000), $3, $4, $5,
                $6::poll_notevisibility_enum, $7, NULL, NULL)
        "#,
    )
    .bind(note_id)
    .bind(expires_at_ms)
    .bind(multiple)
    .bind(choices.to_vec())
    .bind(votes)
    .bind(note_visibility)
    .bind(user_id)
    .execute(pool)
    .await?;
    Ok(())
}

/// `pollsRepository.findOneBy({ noteId })` (populatePoll / vote).
pub async fn find_poll_by_note(
    pool: &PgPool,
    note_id: &str,
) -> Result<Option<PollRow>, sqlx::Error> {
    sqlx::query_as::<_, PollRow>(&format!(
        r#"SELECT {POLL_COLS} FROM "poll" WHERE "noteId" = $1"#
    ))
    .bind(note_id)
    .fetch_optional(pool)
    .await
}

/// `pollVotesRepository.insertOne` (id generated by the caller).
pub async fn insert_poll_vote(
    pool: &PgPool,
    id: &str,
    user_id: &str,
    note_id: &str,
    choice: i32,
) -> Result<(), sqlx::Error> {
    sqlx::query(
        r#"INSERT INTO "poll_vote" ("id", "userId", "noteId", "choice") VALUES ($1, $2, $3, $4)"#,
    )
    .bind(id)
    .bind(user_id)
    .bind(note_id)
    .bind(choice)
    .execute(pool)
    .await?;
    Ok(())
}

/// `pollVotesRepository.findBy({ userId, noteId })` — the choice integers the
/// given user has voted on the note's poll.
pub async fn poll_votes_of_user(
    pool: &PgPool,
    note_id: &str,
    user_id: &str,
) -> Result<Vec<i32>, sqlx::Error> {
    sqlx::query_scalar::<_, i32>(
        r#"SELECT "choice" FROM "poll_vote" WHERE "noteId" = $1 AND "userId" = $2 ORDER BY "id""#,
    )
    .bind(note_id)
    .bind(user_id)
    .fetch_all(pool)
    .await
}

/// `UPDATE poll SET votes[$1] = votes[$1] + 1 WHERE "noteId" = $2` (1-based
/// array addressing in SQL; caller passes the 0-based choice).
pub async fn bump_poll_vote(pool: &PgPool, note_id: &str, choice: i32) -> Result<(), sqlx::Error> {
    sqlx::query(r#"UPDATE "poll" SET "votes"[1 + $2] = ("votes"[1 + $2] + 1) WHERE "noteId" = $1"#)
        .bind(note_id)
        .bind(choice)
        .execute(pool)
        .await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn poll_roundtrip_and_vote_bump() {
        if std::env::var("DATABASE_URL").is_err() {
            return;
        }
        // fresh_db only provisions the database; the poll table rides the
        // explicit migrations (the api-side fresh_pool contract).
        let pool = crate::test_support::fresh_db("mkdb_poll_roundtrip").await;
        crate::run_migrations(&pool).await.unwrap();
        insert_poll(
            &pool,
            "n1",
            &["a".into(), "b".into()],
            false,
            None,
            "public",
            "u1",
        )
        .await
        .unwrap();
        let row = find_poll_by_note(&pool, "n1").await.unwrap().unwrap();
        assert_eq!(row.choices, vec!["a".to_string(), "b".to_string()]);
        assert_eq!(row.votes, vec![0, 0]);
        assert!(row.expires_at_ms.is_none());

        insert_poll_vote(&pool, "v1", "u2", "n1", 1).await.unwrap();
        bump_poll_vote(&pool, "n1", 1).await.unwrap();
        let row = find_poll_by_note(&pool, "n1").await.unwrap().unwrap();
        assert_eq!(row.votes, vec![0, 1]);
        assert_eq!(
            poll_votes_of_user(&pool, "n1", "u2").await.unwrap(),
            vec![1]
        );
    }
}
